import type { Href } from 'expo-router';

/**
 * Shape of {@link Routes}.
 *
 * Typing every leaf as `Href` is what makes the table self-checking: it supplies the
 * contextual type each entry is validated against, so a path that no longer matches the
 * `src/app/` tree fails `npm run type-check`.
 */
export interface RouteTable {
  /** Public screens reachable without a token. */
  public: {
    welcome: Href;
  };
  /** Screens reachable without a token. */
  auth: {
    login: Href;
  };
  /** Root-level, deliberately outside `(auth)`. */
  verifyEmail: Href;
  /** Root-level, deliberately outside `(auth)`. */
  onboarding: Href;
  /** The four tab roots. */
  app: {
    home: Href;
    features: Href;
    profile: Href;
    more: Href;
  };
  profileEdit: Href;
  profileSettings: Href;
  featureDetail: (featureId: string) => Href;
}

/**
 * Every navigable route in the app, named once.
 *
 * Expo Router derives routes from the `src/app/` file tree, so this table is a second,
 * hand-written copy of something the framework already knows. Each entry is written in
 * Expo Router's **object form** (`{ pathname }`), which is what keeps the two in step:
 * the generated route union in `.expo/types/router.d.ts` lists object pathnames as exact
 * literals, so a stale path is a build error rather than a tap that silently does nothing.
 *
 * The string form (`'/(auth)/login'`) is deliberately not used. It looks equivalent but
 * validates nothing — see the note below.
 *
 * Route groups in parentheses do not affect the URL, so a group segment appears here only
 * where the framework needs it to disambiguate. `(home)`, `(features)`, `(profile)` and
 * `(more)` each hold an `index.tsx` and would all otherwise resolve to `/`, so naming a
 * specific tab requires its group. `verify-email` and `onboarding` sit at the root of
 * `src/app/`, in no group at all — they are reachable only once a token exists, because
 * registration returns tokens immediately.
 *
 * @remarks
 * Validation depends on `.expo/types/` existing. It is gitignored and generated by
 * `npx expo customize tsconfig.json` (or any `npx expo start`). Without it, `Href` widens
 * to `string | HrefObject` and every entry below silently passes.
 *
 * String-form hrefs are never validated in this app, whether or not those types exist:
 * `expo-router` takes a bare `Href` in `router.push`/`replace` and `Link`'s `href`, never
 * instantiating its type parameter. `SingleRoutePart<string>` then collapses to `string`,
 * so the dynamic `(app)/(features)/[feature-id]` route contributes a `/${string}` member
 * that swallows any absolute path. `router.replace('/nonsense')` compiles. The object form
 * has no such member.
 */
export const Routes: RouteTable = {
  public: {
    welcome: { pathname: '/(public)' },
  },

  auth: {
    login: { pathname: '/(auth)/login' },
  },

  verifyEmail: { pathname: '/verify-email' },
  onboarding: { pathname: '/onboarding' },

  app: {
    home: { pathname: '/(app)/(home)' },
    features: { pathname: '/(app)/(features)' },
    profile: { pathname: '/(app)/(profile)' },
    more: { pathname: '/(app)/(more)' },
  },

  profileEdit: { pathname: '/(app)/(profile)/edit' },
  profileSettings: { pathname: '/(app)/(profile)/settings' },

  /**
   * Builds the href for a single feature's detail screen.
   *
   * @param featureId - Value for the `[feature-id]` segment of
   * `src/app/(app)/(features)/[feature-id].tsx`.
   * @returns An href targeting that feature's detail screen.
   */
  featureDetail: (featureId: string): Href => ({
    pathname: '/(app)/(features)/[feature-id]',
    params: { 'feature-id': featureId },
  }),
};
