import type { Href } from 'expo-router';
import type { DirectChatFriendSummary } from '@/types/direct-chat.types';

type DirectChatRouteFriend = Pick<DirectChatFriendSummary, 'userId' | 'username' | 'displayName' | 'displayPicture'>;

/**
 * Shape of {@link Routes}.
 *
 * Typing every leaf as `Href` is what makes the table self-checking: it supplies the
 * contextual type each entry is validated against, so a path that no longer matches the
 * `src/app/` tree fails `npm run type-check`.
 */
export interface RouteTable {
  /** Public screens reachable without a token. */
  public: {
    welcome: Href;
    friendShare: (code: string) => Href;
    ganapShare: (ganapId: string) => Href;
  };
  /** Screens reachable without a token. */
  auth: {
    login: Href;
    loginForFriendShare: (code: string) => Href;
    loginForGanapShare: (ganapId: string) => Href;
    /** Builds the public password-recovery route with an optional prefilled email. */
    forgotPassword: (email?: string) => Href;
  };
  /** Root-level, deliberately outside `(auth)`. */
  verifyEmail: Href;
  /** Root-level, deliberately outside `(auth)`. */
  onboarding: Href;
  /** The four tab roots. */
  app: {
    home: Href;
    ganaps: Href;
    chat: Href;
    profile: Href;
  };
  profileEdit: Href;
  profileSettings: Href;
  profileJoined: Href;
  businessProfile: (businessId: string) => Href;
  friendAddWithCode: (code: string) => Href;
  ganapDetail: (ganapId: string, returnTo?: 'my-events') => Href;
  ganapRegistration: (ganapId: string) => Href;
  eventHub: (ganapId: string) => Href;
  eventChat: (ganapId: string) => Href;
  friendProfile: (userId: string) => Href;
  friendSettings: Href;
  directChat: (conversationId: string) => Href;
  directChatForFriend: (friend: DirectChatRouteFriend) => Href;
  attendanceScan: (ganapId: string) => Href;
  ganapFeedback: (ganapId: string) => Href;
}

/**
 * Every navigable route in the app, named once.
 *
 * Expo Router derives routes from the `src/app/` file tree, so this table is a second,
 * hand-written copy of something the framework already knows. Each entry is written in
 * Expo Router's **object form** (`{ pathname }`), which is what keeps the two in step:
 * the generated route union in `.expo/types/router.d.ts` lists object pathnames as exact
 * literals, so a stale path is a build error rather than a tap that silently does nothing.
 *
 * The string form (`'/(auth)/login'`) is deliberately not used. It looks equivalent but
 * validates nothing — see the note below.
 *
 * Route groups in parentheses do not affect the URL, so a group segment appears here only
 * where the framework needs it to disambiguate. Exactly one screen may own `/` — that is
 * `(home)/index.tsx`, the Map tab. The other three tabs name their screen after their group
 * (`(chat)/chat.tsx`), so each owns a distinct URL. See ADR 0001 and DS-34: when several
 * screens resolve to `/`, the router picks one and no initial-route declaration overrides it.
 * `verify-email` and `onboarding` sit at the root of `src/app/`, in no group at all — they
 * are reachable only once a token exists, because registration returns tokens immediately.
 *
 * @remarks
 * Validation depends on `.expo/types/` existing. It is gitignored and generated by
 * `npx expo customize tsconfig.json` (or any `npx expo start`). Without it, `Href` widens
 * to `string | HrefObject` and every entry below silently passes.
 *
 * String-form hrefs are never validated in this app, whether or not those types exist:
 * `expo-router` takes a bare `Href` in `router.push`/`replace` and `Link`'s `href`, never
 * instantiating its type parameter. `SingleRoutePart<string>` then collapses to `string`,
 * so the dynamic `(app)/(home)/[ganap-id]` route contributes a `/${string}` member
 * that swallows any absolute path. The object form has no such member.
 */
export const Routes: RouteTable = {
  public: {
    welcome: { pathname: '/(public)' },
    friendShare: (code: string): Href => ({
      pathname: '/(public)/friends/[code]',
      params: { code },
    }),
    ganapShare: (ganapId: string): Href => ({
      pathname: '/(public)/ganaps/[id]',
      params: { id: ganapId },
    }),
  },

  auth: {
    login: { pathname: '/(auth)/login' },
    loginForFriendShare: (code: string): Href => ({
      pathname: '/(auth)/login',
      params: { returnFriendCode: code },
    }),
    loginForGanapShare: (ganapId: string): Href => ({
      pathname: '/(auth)/login',
      params: { returnGanapId: ganapId },
    }),
    forgotPassword: (email?: string): Href =>
      email ? { pathname: '/(auth)/forgot-password', params: { email } } : { pathname: '/(auth)/forgot-password' },
  },

  verifyEmail: { pathname: '/verify-email' },
  onboarding: { pathname: '/onboarding' },

  app: {
    home: { pathname: '/(app)/(home)' },
    ganaps: { pathname: '/(app)/(ganaps)/ganaps' },
    chat: { pathname: '/(app)/(chat)/chat' },
    profile: { pathname: '/(app)/(profile)/profile' },
  },

  profileEdit: { pathname: '/(app)/(profile)/edit' },
  profileSettings: { pathname: '/(app)/(profile)/settings' },
  profileJoined: { pathname: '/(app)/(profile)/joined' },

  /** Builds an authenticated organization profile route.
   * @param businessId - Business identity from the Ganap
   * @returns Pushed organization profile href
   */
  businessProfile: (businessId: string): Href => ({
    pathname: '/(app)/(home)/organizations/[business-id]',
    params: { 'business-id': businessId },
  }),

  /** Builds the Chat tab route with the Add Friend form prefilled with one Friend Code. */
  friendAddWithCode: (code: string): Href => ({
    pathname: '/(app)/(chat)/chat',
    params: { friendCode: code },
  }),

  /**
   * Builds the href for a single event's detail screen.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of
   * `src/app/(app)/(home)/[ganap-id].tsx`.
   * @param returnTo - Optional My Events destination for the detail screen's back action.
   * @returns An href targeting that event's detail screen.
   */
  ganapDetail: (ganapId: string, returnTo?: 'my-events'): Href => ({
    pathname: '/(app)/(home)/[ganap-id]',
    params: returnTo === undefined ? { 'ganap-id': ganapId } : { 'ganap-id': ganapId, returnTo },
  }),

  /**
   * Builds the href for a Ganap's registration form.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of the registration route.
   * @returns An href targeting the registration form screen.
   */
  ganapRegistration: (ganapId: string): Href => ({
    pathname: '/(app)/(home)/registration/[ganap-id]',
    params: { 'ganap-id': ganapId },
  }),

  /**
   * Builds the href for a Ganap's Event Hub screen.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of the Event Hub route.
   * @returns An href targeting that event's Event Hub screen.
   */
  eventHub: (ganapId: string): Href => ({
    pathname: '/(app)/(home)/event-hub/[ganap-id]',
    params: { 'ganap-id': ganapId },
  }),

  /**
   * Builds the href for an Event Chat thread.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of the chat thread route.
   * @returns An href targeting the Ganap's Event Chat thread.
   */
  eventChat: (ganapId: string): Href => ({
    pathname: '/(app)/(chat)/event-chat/[ganap-id]',
    params: { 'ganap-id': ganapId },
  }),

  /**
   * Builds the href for a relationship-scoped Friend profile.
   *
   * @param userId - User identifier for the `[user-id]` profile route.
   * @returns An href targeting the Friend profile screen.
   */
  friendProfile: (userId: string): Href => ({
    pathname: '/(app)/(chat)/friend-profile/[user-id]',
    params: { 'user-id': userId },
  }),

  /** Href for the Friends privacy settings screen. */
  friendSettings: { pathname: '/(app)/(chat)/friend-settings' },
  /**
   * Builds an href for an existing canonical Direct Chat conversation.
   *
   * @param conversationId - Canonical Direct conversation id
   * @returns An href targeting the Direct Chat thread
   */
  directChat: (conversationId: string): Href => ({
    pathname: '/(app)/(chat)/direct-chat/[conversation-id]',
    params: { 'conversation-id': conversationId },
  }),

  /**
   * Builds the lazy Direct Chat entry point from an accepted friend's profile.
   *
   * The `new` marker is route-local only; the client does not create a server
   * conversation until the first successful send.
   *
   * @param friend - Accepted friend's safe identity for the new thread header
   * @returns An href targeting the lazy Direct Chat composer
   */
  directChatForFriend: (friend: DirectChatRouteFriend): Href => ({
    pathname: '/(app)/(chat)/direct-chat/[conversation-id]',
    params: {
      'conversation-id': 'new',
      'friend-user-id': friend.userId,
      'friend-username': friend.username,
      'friend-display-name': friend.displayName,
      'friend-display-picture': friend.displayPicture ?? '',
    },
  }),

  /**
   * Builds the href for a Ganap's attendance scanner screen.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of the scan route.
   * @returns An href targeting that event's attendance scanner.
   */
  attendanceScan: (ganapId: string): Href => ({
    pathname: '/(app)/(home)/scan/[ganap-id]',
    params: { 'ganap-id': ganapId },
  }),

  /**
   * Builds the href for a Ganap's post-event feedback flow.
   *
   * @param ganapId - Value for the `[ganap-id]` segment of the feedback route.
   * @returns An href targeting that event's rating and feedback screen.
   */
  ganapFeedback: (ganapId: string): Href => ({
    pathname: '/(app)/(home)/feedback/[ganap-id]',
    params: { 'ganap-id': ganapId },
  }),
};
